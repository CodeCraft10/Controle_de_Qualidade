CREATE TABLE usuarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(200) NOT NULL CHECK (btrim(nome) <> ''),
    email varchar(254) NOT NULL CHECK (btrim(email) <> ''),
    senha_hash text NOT NULL,
    perfil text NOT NULL CHECK (perfil IN ('admin', 'supervisor', 'inspetor')),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX usuarios_email_lower_uq ON usuarios (lower(email));

CREATE TABLE produtos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(80) NOT NULL CHECK (btrim(codigo) <> ''),
    nome varchar(200) NOT NULL CHECK (btrim(nome) <> ''),
    descricao varchar(3000) NOT NULL DEFAULT '',
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX produtos_codigo_lower_uq ON produtos(lower(codigo));

CREATE TABLE lotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(80) NOT NULL CHECK (btrim(codigo) <> ''),
    produto_id bigint NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT,
    quantidade bigint NOT NULL CHECK (quantidade > 0),
    data_fabricacao date NOT NULL,
    status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aprovado', 'reprovado')),
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, produto_id)
);
CREATE UNIQUE INDEX lotes_codigo_lower_uq ON lotes(lower(codigo));
CREATE INDEX lotes_produto_id_idx ON lotes(produto_id);
CREATE INDEX lotes_status_idx ON lotes(status);

CREATE TABLE criterios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(200) NOT NULL CHECK (btrim(nome) <> ''),
    descricao varchar(3000) NOT NULL DEFAULT '',
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX criterios_nome_lower_uq ON criterios(lower(nome));

CREATE TABLE checklists (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(200) NOT NULL CHECK (btrim(nome) <> ''),
    descricao varchar(3000) NOT NULL DEFAULT '',
    ativo boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX checklists_nome_lower_uq ON checklists(lower(nome));

CREATE TABLE checklist_itens (
    checklist_id bigint NOT NULL REFERENCES checklists(id) ON DELETE RESTRICT,
    item_id integer NOT NULL CHECK (item_id > 0),
    criterio_id bigint NOT NULL REFERENCES criterios(id) ON DELETE RESTRICT,
    obrigatorio boolean NOT NULL DEFAULT true,
    criado_em timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (checklist_id, item_id),
    UNIQUE (checklist_id, criterio_id),
    UNIQUE (checklist_id, item_id, criterio_id)
);
CREATE INDEX checklist_itens_criterio_idx ON checklist_itens(criterio_id);

CREATE TABLE inspecoes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id bigint NOT NULL UNIQUE REFERENCES lotes(id) ON DELETE RESTRICT,
    checklist_id bigint NOT NULL REFERENCES checklists(id) ON DELETE RESTRICT,
    inspetor_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    produto_id bigint NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT,
    produto_nome_snapshot varchar(200) NOT NULL,
    lote_codigo_snapshot varchar(80) NOT NULL,
    checklist_nome_snapshot varchar(200) NOT NULL,
    status text NOT NULL DEFAULT 'em_andamento' CHECK (status IN ('em_andamento', 'aprovada', 'reprovada')),
    iniciada_em timestamptz NOT NULL DEFAULT now(),
    finalizada_em timestamptz,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CHECK ((status = 'em_andamento' AND finalizada_em IS NULL) OR (status <> 'em_andamento' AND finalizada_em IS NOT NULL)),
    UNIQUE (id, checklist_id),
    FOREIGN KEY (lote_id, produto_id) REFERENCES lotes(id, produto_id) ON DELETE RESTRICT
);
CREATE INDEX inspecoes_iniciada_em_idx ON inspecoes(iniciada_em);
CREATE INDEX inspecoes_lote_idx ON inspecoes(lote_id);
CREATE INDEX inspecoes_produto_idx ON inspecoes(produto_id);
CREATE INDEX inspecoes_inspetor_idx ON inspecoes(inspetor_id);
CREATE INDEX inspecoes_status_idx ON inspecoes(status);

CREATE TABLE inspecao_itens (
    inspecao_id bigint NOT NULL REFERENCES inspecoes(id) ON DELETE RESTRICT,
    checklist_id bigint NOT NULL,
    item_id integer NOT NULL CHECK (item_id > 0),
    criterio_id bigint NOT NULL REFERENCES criterios(id) ON DELETE RESTRICT,
    criterio_nome_snapshot varchar(200) NOT NULL,
    criterio_descricao_snapshot varchar(3000) NOT NULL DEFAULT '',
    obrigatorio boolean NOT NULL,
    PRIMARY KEY (inspecao_id, item_id),
    FOREIGN KEY (inspecao_id, checklist_id) REFERENCES inspecoes(id, checklist_id) ON DELETE RESTRICT,
    FOREIGN KEY (checklist_id, item_id, criterio_id) REFERENCES checklist_itens(checklist_id, item_id, criterio_id) ON DELETE RESTRICT
);
CREATE INDEX inspecao_itens_criterio_idx ON inspecao_itens(criterio_id);

CREATE TABLE respostas_inspecao (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspecao_id bigint NOT NULL,
    item_id integer NOT NULL,
    resultado text NOT NULL CHECK (resultado IN ('conforme', 'nao_conforme', 'nao_aplicavel')),
    observacao varchar(3000) NOT NULL DEFAULT '',
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (inspecao_id, item_id) REFERENCES inspecao_itens(inspecao_id, item_id) ON DELETE RESTRICT,
    UNIQUE (inspecao_id, item_id),
    UNIQUE (id, inspecao_id, item_id),
    CHECK (resultado <> 'nao_aplicavel' OR btrim(observacao) <> '')
);

CREATE TABLE nao_conformidades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resposta_id bigint NOT NULL UNIQUE,
    inspecao_id bigint NOT NULL,
    item_id integer NOT NULL,
    descricao varchar(3000) NOT NULL CHECK (btrim(descricao) <> ''),
    classificacao text NOT NULL DEFAULT 'menor' CHECK (classificacao IN ('menor', 'maior', 'critica')),
    status text NOT NULL DEFAULT 'aberta' CHECK (status IN ('aberta', 'em_tratamento', 'resolvida')),
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (resposta_id, inspecao_id, item_id) REFERENCES respostas_inspecao(id, inspecao_id, item_id) ON DELETE RESTRICT
);
CREATE INDEX nao_conformidades_inspecao_idx ON nao_conformidades(inspecao_id);
CREATE INDEX nao_conformidades_status_idx ON nao_conformidades(status);

CREATE TABLE historico_nao_conformidade (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nao_conformidade_id bigint NOT NULL REFERENCES nao_conformidades(id) ON DELETE RESTRICT,
    status text NOT NULL CHECK (status IN ('aberta', 'em_tratamento', 'resolvida')),
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    observacao varchar(3000) NOT NULL DEFAULT '',
    criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX historico_nc_parent_idx ON historico_nao_conformidade(nao_conformidade_id, criado_em);

CREATE TABLE evidencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nao_conformidade_id bigint NOT NULL REFERENCES nao_conformidades(id) ON DELETE RESTRICT,
    nome_original varchar(200) NOT NULL,
    mime text NOT NULL CHECK (mime IN ('image/jpeg', 'image/png', 'image/webp')),
    tamanho bigint NOT NULL CHECK (tamanho > 0 AND tamanho <= 5242880),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    conteudo bytea NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CHECK (tamanho = octet_length(conteudo))
);
CREATE INDEX evidencias_nc_idx ON evidencias(nao_conformidade_id);

CREATE TABLE acoes_corretivas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nao_conformidade_id bigint NOT NULL REFERENCES nao_conformidades(id) ON DELETE RESTRICT,
    descricao varchar(3000) NOT NULL CHECK (btrim(descricao) <> ''),
    responsavel_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    prazo date,
    status text NOT NULL DEFAULT 'aberta' CHECK (status IN ('aberta', 'em_andamento', 'concluida', 'cancelada')),
    conclusao varchar(3000) NOT NULL DEFAULT '',
    criada_por bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX acoes_corretivas_nc_idx ON acoes_corretivas(nao_conformidade_id);
CREATE INDEX acoes_corretivas_status_prazo_idx ON acoes_corretivas(status, prazo);

CREATE TABLE historico_acao_corretiva (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao_corretiva_id bigint NOT NULL REFERENCES acoes_corretivas(id) ON DELETE RESTRICT,
    status text NOT NULL CHECK (status IN ('aberta', 'em_andamento', 'concluida', 'cancelada')),
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    observacao varchar(3000) NOT NULL DEFAULT '',
    criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX historico_acao_parent_idx ON historico_acao_corretiva(acao_corretiva_id, criado_em);

CREATE TABLE historico_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint REFERENCES usuarios(id) ON DELETE RESTRICT,
    acao text NOT NULL,
    recurso text NOT NULL,
    recurso_id bigint NOT NULL,
    detalhes jsonb NOT NULL DEFAULT '{}'::jsonb,
    criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX auditoria_recurso_idx ON historico_auditoria(recurso, recurso_id, criado_em);
CREATE INDEX auditoria_usuario_idx ON historico_auditoria(usuario_id, criado_em);

CREATE TABLE sessoes (
    token_hash char(64) PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira_em timestamptz NOT NULL,
    criado_em timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessoes_expira_em_idx ON sessoes(expira_em);

CREATE TABLE tentativas_login (
    ip_hash char(64) PRIMARY KEY CHECK (ip_hash ~ '^[0-9a-f]{64}$'),
    inicio_em timestamptz NOT NULL,
    quantidade integer NOT NULL CHECK (quantidade >= 0),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);


